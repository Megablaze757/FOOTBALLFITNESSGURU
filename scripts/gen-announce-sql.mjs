// =============================================================================
// Render the launch email into a SQL-only sender.
//
// WHY THIS EXISTS. Deploying an Edge Function needs a terminal, or a CI secret,
// or the dashboard's function editor. None of those are available to someone
// holding a phone, and "wait until you're at a laptop" is a bad answer to "can
// we use what we already have" — because we can. This project already documents
// pg_net + pg_cron + Vault (supabase/cron/schedule.sql), which means the
// database can make HTTP calls on its own. Resend has an HTTP API. That is the
// whole trick: the send becomes SQL you paste into the SQL editor.
//
// THE COPY HAS EXACTLY ONE SOURCE. The email is rendered here from
// supabase/functions/announce-launch/email.ts — the same module the Edge
// Function uses — with two placeholders left in it for the per-recipient link
// and unsubscribe URL. Writing the HTML out a second time by hand is how the
// two versions start disagreeing, and nobody notices until half the list got
// the old wording.
//
//   node scripts/gen-announce-sql.mjs > /tmp/announce.sql
// =============================================================================

import { createHash } from "node:crypto";

import { launchEmail } from "../supabase/functions/announce-launch/email.ts";

const APP_URL = process.env.APP_URL || "https://pocketathlete.com";

// Rendered once with sentinels, then substituted per row in SQL. The sentinels
// are deliberately not URL-shaped so a stray one is obvious in an inbox rather
// than looking like a broken link.
const CTA = "@@CTA@@";
const UNSUB = "@@UNSUB@@";
const mail = launchEmail({ appUrl: APP_URL, ref: null, unsubscribeUrl: UNSUB });

// launchEmail builds the CTA itself, so swap the ref-less URL it produced for
// the sentinel. Asserted rather than assumed — a silent miss here ships every
// email pointing at the same un-attributed link.
const plainCta = `${APP_URL}/`;
function withCta(s) {
  const out = s.split(plainCta).join(CTA);
  if (!out.includes(CTA)) throw new Error("CTA placeholder not substituted — email.ts changed shape");
  return out;
}
const html = withCta(mail.html);
const text = withCta(mail.text);

/**
 * A fingerprint of the copy, carried inside the function body as a comment.
 *
 * WHY. "Did the paste take?" was answered by eyeballing an inbox, and the answer
 * was wrong twice — once because regenerating the repo file never touched the
 * database at all, and once because a paste silently did not run. prosrc keeps
 * comments verbatim, so stamping the id into the body makes the question exact
 * and answerable in SQL: the id in the database either matches the copy you
 * just pasted or it does not.
 *
 * Derived from the rendered email rather than from a version anyone maintains
 * by hand, because a number you have to remember to bump is a number that does
 * not get bumped.
 */
const copyId = createHash("sha256")
  .update(`${mail.subject}\n${html}\n${text}`)
  .digest("hex")
  .slice(0, 12);

/** Postgres dollar-quoting, with a tag that cannot appear in the body. */
function dollar(s) {
  let tag = "$mail$";
  let i = 0;
  while (s.includes(tag)) tag = `$mail${++i}$`;
  return `${tag}${s}${tag}`;
}

// Three sections, so the sender can be emitted on its own.
//
// WHY THAT MATTERS. The email HTML is baked into the function body as a string
// literal, which means changing a word of copy requires replacing the whole
// function in the database — the repo file going stale is not the failure mode,
// the DATABASE going stale is. That happened: the copy was rewritten, every
// checked-in artifact regenerated, and the button kept sending the old email
// because nothing had pushed the new function into Postgres.
//
// `--email-only` emits just the sender and its grants, for exactly that case.
// It is `create or replace`, so it overwrites in place and needs no teardown,
// and it is under half the size — which matters when the person pasting it is
// on a phone.
const HEADER = `-- =============================================================================
-- Launch announcement, sent from the database.
--
-- GENERATED by scripts/gen-announce-sql.mjs from the same email module the Edge
-- Function uses. Do not hand-edit the copy below — regenerate it, or the two
-- senders drift apart.
--
-- Needs: pg_net (Database → Extensions) and the Resend key in Vault.
-- =============================================================================

create extension if not exists pg_net;

-- --- The key -------------------------------------------------------------------
-- FIRST, CHECK WHETHER IT IS ALREADY HERE. This lists names only, never values:
--
--   select name, created_at from vault.secrets order by created_at;
--
-- If you see resend_api_key (or RESEND_API_KEY / resend / RESEND) you are done —
-- the function below accepts any of those spellings.
--
-- IF IT IS NOT THERE, that is expected even though your reminder emails work.
-- Those are Edge Functions reading Deno.env.get('RESEND_API_KEY'), which is a
-- function-runtime secret. Postgres cannot read it. Same key, different store.
-- Add it here once:
--
--   select vault.create_secret('re_xxx', 'resend_api_key');
--
-- Changing one that already exists:
--   select vault.update_secret(id, 're_new') from vault.secrets where name = 'resend_api_key';

-- --- Installing the key from the admin screen ---------------------------------
--
-- So the key can be stored without opening a SQL editor. The person doing this
-- is usually on a phone, and "paste this into the SQL editor" is a worse
-- instruction than "paste it into the box".

create or replace function public.set_resend_key(p_key text)
returns text
language plpgsql
security definer
set search_path = public, pg_temp, vault
as $key$
declare
  v_id uuid;
begin
  if not public.is_admin() then
    raise exception 'forbidden' using errcode = '42501';
  end if;
  if coalesce(trim(p_key), '') = '' then
    raise exception 'no key given';
  end if;

  select id into v_id from vault.secrets where name = 'resend_api_key';
  if v_id is null then
    perform vault.create_secret(trim(p_key), 'resend_api_key');
    return 'stored';
  else
    perform vault.update_secret(v_id, trim(p_key));
    return 'replaced';
  end if;
end;
$key$;

revoke execute on function public.set_resend_key(text) from public, anon;
grant  execute on function public.set_resend_key(text) to authenticated;

/**
 * Whether a key is present. Never returns the key itself — the admin screen
 * only needs to know whether to show the box, and a function that hands back a
 * secret is one that eventually gets called by something that should not.
 */
create or replace function public.has_resend_key()
returns boolean
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $has$
begin
  if not public.is_admin() then
    raise exception 'forbidden' using errcode = '42501';
  end if;
  return exists (
    select 1 from vault.decrypted_secrets
     where name in ('resend_api_key', 'RESEND_API_KEY', 'resend', 'RESEND')
       and coalesce(decrypted_secret, '') <> ''
  );
end;
$has$;

revoke execute on function public.has_resend_key() from public, anon;
grant  execute on function public.has_resend_key() to authenticated;

`;

const SENDER = `-- --- The sender ---------------------------------------------------------------

create or replace function public.announce_launch(
  p_limit    int  default 50,
  p_test_to  text default null,
  -- MATCHES cloudflare/wrangler.toml's REMINDER_FROM, which is the address the
  -- Worker's reminder emails already go out from — so it is a mailbox on a
  -- domain Resend has already verified. The default used to be hello@, which
  -- nothing sends from: a launch blast is the worst possible moment to find out
  -- an address is unconfigured, and the failure would be one opaque 4xx per
  -- recipient.
  p_from     text default 'PocketAthlete <info@pocketathlete.com>'
)
returns table (emailed int, remaining int, note text)
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
declare
  -- copy-id: ${copyId}
  -- Fingerprint of the email copy below, kept where Postgres stores it verbatim.
  -- The self-check at the bottom of announce-launch-update.sql looks for exactly
  -- this string, which is how you tell a paste that took from one that did not.
  v_key   text;
  v_html  text := ${dollar(html)};
  v_text  text := ${dollar(text)};
  v_subj  text := ${dollar(mail.subject)};
  v_app   text := ${dollar(APP_URL)};
  r       record;
  v_cta   text;
  v_unsub text;
  v_sent  int := 0;
  v_left  int;
begin
  if not public.is_admin() then
    raise exception 'forbidden' using errcode = '42501';
  end if;

  -- SEVERAL NAMES, because the key may already be here under one of them.
  -- Vault is not where the Edge Functions keep theirs — those read
  -- Deno.env.get('RESEND_API_KEY'), which is a function-runtime secret that
  -- Postgres cannot see. Same key, different cupboard. Checking the obvious
  -- spellings costs nothing and saves a confusing "it is already set" round.
  select decrypted_secret into v_key
    from vault.decrypted_secrets
   where name in ('resend_api_key', 'RESEND_API_KEY', 'resend', 'RESEND')
   order by case name when 'resend_api_key' then 0 else 1 end
   limit 1;

  if v_key is null then
    raise exception
      'No Resend key in Vault. See what is there:  select name from vault.secrets;  '
      'Then add it:  select vault.create_secret(''re_xxx'', ''resend_api_key'');  '
      'Note this is separate from the Edge Function secret of the same name - Postgres cannot read those.';
  end if;

  -- ONE ADDRESS, TOUCHING NOTHING. Returns before the real query so a test can
  -- be fired as often as you like while tweaking the copy — if it consumed a
  -- place in the batch, checking the email would remove people from the send it
  -- was checking.
  if p_test_to is not null then
    v_cta   := v_app || '/';
    v_unsub := v_app || '/unsubscribe?t=' || gen_random_uuid()::text;
    perform net.http_post(
      url     := 'https://api.resend.com/emails',
      headers := jsonb_build_object('Content-Type', 'application/json',
                                    'Authorization', 'Bearer ' || v_key),
      body    := jsonb_build_object(
        'from', p_from, 'to', p_test_to,
        'subject', '[TEST] ' || v_subj,
        'html', replace(replace(v_html, '@@CTA@@', v_cta), '@@UNSUB@@', v_unsub),
        'text', replace(replace(v_text, '@@CTA@@', v_cta), '@@UNSUB@@', v_unsub))
    );
    return query select 0, 0,
      'Test queued to ' || p_test_to || '. Nobody on the waitlist was emailed, marked or skipped.';
    return;
  end if;

  -- Never anyone who left, never anyone already told. The stamp is what makes
  -- pressing this twice safe, and it is why it can be run in batches.
  for r in
    select w.id, w.email, w.unsub_token,
           coalesce(nullif(trim(w.referral_code), ''), nullif(trim(w.source), '')) as ref
      from public.waitlist w
     where w.unsubscribed_at is null
       and w.launch_emailed_at is null
     order by w.created_at
     limit greatest(1, p_limit)
  loop
    -- The affiliate code that brought them in. Attribution does not depend on
    -- it — 0057 binds the email to its referrer permanently and signup reads
    -- that ledger — but it covers someone signing up with a different address.
    v_cta := v_app || '/' || coalesce('?ref=' || r.ref, '');
    v_unsub := v_app || '/unsubscribe?t=' || r.unsub_token::text;

    perform net.http_post(
      url     := 'https://api.resend.com/emails',
      headers := jsonb_build_object('Content-Type', 'application/json',
                                    'Authorization', 'Bearer ' || v_key),
      body    := jsonb_build_object(
        'from', p_from, 'to', r.email, 'subject', v_subj,
        'html', replace(replace(v_html, '@@CTA@@', v_cta), '@@UNSUB@@', v_unsub),
        'text', replace(replace(v_text, '@@CTA@@', v_cta), '@@UNSUB@@', v_unsub),
        -- Gmail and Yahoo require one-click unsubscribe on bulk mail. Without
        -- it this send damages deliverability for password resets too.
        'headers', jsonb_build_object(
          'List-Unsubscribe', '<' || v_unsub || '>',
          'List-Unsubscribe-Post', 'List-Unsubscribe=One-Click'))
    );

    -- pg_net is FIRE AND FORGET: http_post queues the request and returns
    -- immediately, so there is no delivery to confirm inside this loop. Stamped
    -- optimistically, which is the right trade — a duplicate is worse than a
    -- miss here, and the reconcile query below finds anything Resend refused.
    update public.waitlist set launch_emailed_at = now() where id = r.id;
    v_sent := v_sent + 1;
  end loop;

  select count(*) into v_left from public.waitlist
   where unsubscribed_at is null and launch_emailed_at is null;

  return query select v_sent, v_left,
    case when v_left > 0
      then 'Queued ' || v_sent || '. ' || v_left || ' still to go — run it again.'
      else 'Queued ' || v_sent || '. Nobody left to email.' end;
end;
$fn$;

revoke execute on function public.announce_launch(int, text, text) from public, anon;
grant  execute on function public.announce_launch(int, text, text) to authenticated;
`;

const HOWTO = `
-- =============================================================================
-- HOW TO USE IT
--
--   1. Test it on yourself. Sends one email, changes nothing:
--        select * from public.announce_launch(p_test_to => 'you@example.com');
--
--   2. See who is queued up, without sending:
--        select count(*) from public.waitlist
--         where unsubscribed_at is null and launch_emailed_at is null;
--
--   3. Send. Start small — 5 proves the whole path before it costs anything:
--        select * from public.announce_launch(5);
--        select * from public.announce_launch(50);   -- repeat until 0 remain
--
--   4. Did they actually go? pg_net records every response:
--        select r.status_code, count(*)
--          from net._http_response r
--         where r.created > now() - interval '1 hour'
--         group by 1;
--
--   5. Anything Resend refused was still marked as sent, because pg_net cannot
--      report failure synchronously. This puts those back in the queue — but
--      only run it if step 4 shows non-2xx responses, or you will re-send to
--      people who received it:
--        -- update public.waitlist set launch_emailed_at = null
--        --  where launch_emailed_at > now() - interval '1 hour';
-- =============================================================================
`;

/**
 * The verdict, appended to BOTH files.
 *
 * WHY BOTH. The full installer used to end on a grant, and a grant makes the
 * Supabase SQL editor say "Success. No rows returned." That is indistinguishable
 * from having pasted a stale copy of this file — which is precisely what
 * happened: an older announce-launch.sql was pasted several times, reported
 * success each time, and reinstalled the previous email on every run. Nothing
 * in the output could have told anyone.
 *
 * Now every file that installs the sender ends by saying which copy is now
 * live. "No rows returned" therefore means the file was not this one.
 */
const VERDICT = `
-- --- Did it take? -------------------------------------------------------------
-- Reads one row from the catalogue. Sends nothing, changes nothing.
--
-- THIS ALWAYS RETURNS EXACTLY ONE ROW. If your SQL editor said "Success. No
-- rows returned", you pasted a different (older) file — check you are on the
-- right branch, because the copy lives inside the function body and an old file
-- silently reinstalls the old email.

select case
         when p.prosrc like '%copy-id: ${copyId}%'
           then 'INSTALLED - new copy is live (copy-id ${copyId}). Send yourself a test.'
         when p.prosrc is not null
           then 'NOT INSTALLED - announce_launch still holds different copy. Re-paste this whole file.'
       end as result
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
 where p.proname = 'announce_launch' and n.nspname = 'public';
`;

// The full install: docs, key management, the sender, then the verdict.
const FULL = HEADER + SENDER + VERDICT + HOWTO;

// Just the sender. For a database that already has the key and the helper
// functions and only needs the copy refreshed.
const UPDATE = `-- =============================================================================
-- Refresh the launch email copy. NOTHING IS SENT BY RUNNING THIS.
--
-- GENERATED by scripts/gen-announce-sql.mjs --email-only. The email HTML lives
-- inside the function body, so new wording only reaches the database when the
-- function is replaced — regenerating the repo file does not touch Postgres,
-- and the button will keep sending the previous copy until this is run.
--
-- Safe to run repeatedly: create or replace, no drop, no data touched. It does
-- not clear launch_emailed_at, so anyone already emailed stays emailed.
--
-- The last statement checks itself and prints the verdict, so there is nothing
-- to remember to run afterwards and nothing to eyeball in an inbox.
-- =============================================================================

${SENDER}${VERDICT}`;

process.stdout.write(process.argv.includes("--email-only") ? UPDATE : FULL);
